function isLocked(item) {
  return item.level === 2 || item.cost > state.coins;
}

function rewardCardHtml(item) {
  const locked = isLocked(item);
  const inCart = state.cart.includes(item.id);
  const classes = ['reward-card', item.sale && 'sale-card', locked && 'locked-card'].filter(Boolean).join(' ');
  const saleBadge = item.sale ? '<span class="sale-badge">25%</span>' : '';
  const priceHtml = item.sale
    ? `<div class="cost sale-cost"><span><img src="assets/icons/coin-sale.svg" alt="">${item.cost}</span><del><img src="assets/icons/coin-muted.svg" alt="">${item.saleCost}</del></div>`
    : `<div class="cost"><span><img src="assets/icons/coin.svg" alt="">${item.cost}</span></div>`;
  const footerHtml = locked
    ? `<div class="reward-footer"><span>${t('notEnoughCoins')}</span><button class="locked-button">${t('lockedButton')}</button></div>`
    : inCart
      ? `<div class="reward-footer"><a href="#terms">${t('termsConditions')}</a><button class="add-button added" data-action="open-cart" aria-label="In cart, view cart"><img src="assets/icons/cart.svg" alt=""></button></div>`
      : `<div class="reward-footer"><a href="#terms">${t('termsConditions')}</a><button class="add-button" data-action="add" data-id="${item.id}"><img src="assets/icons/cart.svg" alt="">${t('addButton')}</button></div>`;
  return `<article class="${classes}">
    <img class="game-thumb" src="${item.img}" alt="${item.game}">
    ${saleBadge}
    <div class="reward-copy"><h3>${translateRewardName(item.name)}</h3><p>${item.game}<br>${item.sub}</p></div>
    ${priceHtml}
    ${footerHtml}
  </article>`;
}

function getFilterLabel(filter) {
  switch (filter) {
    case 'level1': return t('lvl1Rewards');
    case 'level2': return t('lvl2RewardsShort');
    case 'freeSpins': return t('filterFreeSpins');
    case 'cashback': return t('filterCashback');
    default: return t('filterAll');
  }
}

function matchesFilter(item) {
  switch (state.filter) {
    case 'level1': return item.level === 1;
    case 'level2': return item.level === 2;
    case 'freeSpins': return item.name.toLowerCase().includes('free spins');
    case 'cashback': return item.name.trim().startsWith('€');
    default: return true;
  }
}

function renderRewards() {
  const l1 = document.getElementById('level1-rewards-list');
  const l2 = document.getElementById('level2-rewards-list');
  if (!l1 || !l2) return;
  const l1Items = CATALOG.filter((item) => item.level === 1 && matchesFilter(item));
  const l2Items = CATALOG.filter((item) => item.level === 2 && matchesFilter(item));
  l1.innerHTML = l1Items.map(rewardCardHtml).join('') || `<p class="empty-hint">${t('noRewardsMatchFilter')}</p>`;
  l2.innerHTML = l2Items.map(rewardCardHtml).join('') || `<p class="empty-hint">${t('noRewardsMatchFilter')}</p>`;

  const label = document.getElementById('live-filter-label');
  if (label) label.textContent = getFilterLabel(state.filter);
  document.querySelectorAll('.select-list[data-live] li').forEach((li) => {
    li.classList.toggle('active', li.dataset.filter === state.filter);
  });
}

