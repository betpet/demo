function isFreeSpinsItem(name) {
  return /free spins/i.test(name);
}

function extractSpinsCount(name) {
  const match = name.match(/(\d+)\s*Free Spins/i);
  return match ? Number(match[1]) : null;
}

function purchasedCardHtml({ id, name, game, sub, img, tagKey }) {
  const playable = tagKey === 'purchasedTag' && isFreeSpinsItem(name);
  const playButton = playable ? `<button class="btn-play" data-action="play" data-id="${id}">${t('playButton')}</button>` : '';
  return `<article class="reward-card purchased"><img class="game-thumb" src="${img}" alt=""><div class="reward-copy"><h3>${translateRewardName(name)}</h3><p>${game}<br>${sub}</p></div><div class="purchased-side"><span class="purchased-tag">${t(tagKey)}</span>${playButton}</div></article>`;
}

function renderPurchased() {
  const list = document.getElementById('live-purchased-list');
  const historyList = document.getElementById('live-history-list');
  if (!list || !historyList) return;
  list.innerHTML = state.purchased.length
    ? state.purchased.map((id) => {
        const item = findItem(id);
        return item ? purchasedCardHtml({ ...item, tagKey: 'purchasedTag' }) : '';
      }).join('')
    : `<p class="empty-hint">${t('emptyPurchasedHint')}</p>`;
  const redeemedItems = state.redeemed.map((id) => findItem(id)).filter(Boolean);
  historyList.innerHTML = [...redeemedItems, ...HISTORY_SEED]
    .map((h) => purchasedCardHtml({ ...h, tagKey: 'redeemedTag' }))
    .join('');
}

function renderLiveScreens() {
  renderRewards();
  renderCoins();
  renderCartBadge();
  renderCartModal();
  renderPurchased();
  updateToasterContent();
  updatePurchaseModalContent();
}

// Drives the offers-toast-2 "You received" title with the actual spin count of
// whichever purchased reward the player chose to "Play", falling back to the
// original static Figma demo content when none is active.
function updateToasterContent() {
  const titleEl = document.querySelector('#screen-offers-toast-2 .toaster-modal h3');
  if (!titleEl) return;
  titleEl.innerHTML = activePlay ? t('youReceivedSpinsTitle')(activePlay.spins) : t('toasterReceivedTitle');
}

function playReward(id) {
  const item = findItem(id);
  if (!item || !state.purchased.includes(id)) return;
  const spins = extractSpinsCount(item.name) || 10;
  activePlay = { id, item, spins };
  goto('offers-toast-1');
}

function completePlay() {
  if (!activePlay) { goto('all-offers'); return; }
  const { id, item, spins } = activePlay;
  const idx = state.purchased.indexOf(id);
  if (idx !== -1) state.purchased.splice(idx, 1);
  state.redeemed.push(id);
  activePlay = null;
  saveState();
  goto('cart-purchased-1');
  showToast(t('spinsUsedToast')(spins, item.game));
}

function showToast(message) {
  const stack = document.getElementById('toast-stack');
  if (!stack) return;
  const el = document.createElement('div');
  el.className = 'notification-banner floating';
  el.innerHTML = message + '<button class="banner-close" aria-label="Dismiss">×</button>';
  stack.appendChild(el);
  const dismiss = () => {
    el.classList.add('dismissed');
    setTimeout(() => el.remove(), 300);
  };
  el.querySelector('.banner-close').addEventListener('click', dismiss);
  setTimeout(dismiss, 5000);
}

function addToCart(id) {
  const item = findItem(id);
  if (!item || isLocked(item) || state.cart.includes(id)) return;
  state.cart.push(id);
  state.coins -= item.cost;
  saveState();
  renderLiveScreens();
  showToast(t('addedToCartToast')(translateRewardName(item.name), item.game));
}

function removeFromCart(id) {
  const idx = state.cart.indexOf(id);
  if (idx === -1) return;
  const item = findItem(id);
  state.cart.splice(idx, 1);
  if (item) state.coins += item.cost;
  saveState();
  renderLiveScreens();
  if (state.cart.length === 0) goto('rewards-1');
}

function checkout() {
  if (state.cart.length === 0) return;
  const purchasedIds = [...state.cart];
  state.purchased.push(...purchasedIds);
  state.cart = [];
  saveState();
  renderLiveScreens();
  goto('cart-purchased-1');
  const spinsItem = purchasedIds.map(findItem).find((item) => item && isFreeSpinsItem(item.name));
  if (spinsItem) openPurchaseModal(spinsItem);
  else showToast(t('purchaseCompleteToast'));
}

function setFilter(filter) {
  state.filter = filter;
  saveState();
  renderRewards();
  toggleFilterDropdown(false);
}

function toggleFilterDropdown(force) {
  const wrap = document.getElementById('live-filter-wrap');
  if (!wrap) return;
  const show = force !== undefined ? force : !wrap.classList.contains('open');
  wrap.classList.toggle('open', show);
  const chevron = wrap.querySelector('.chevron');
  if (chevron) chevron.classList.toggle('up', show);
}

