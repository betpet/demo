const LANG_KEY = 'pLevelsLang';
let currentLang = (() => {
  try { return localStorage.getItem(LANG_KEY) === 'en' ? 'en' : 'es'; } catch (err) { return 'es'; }
})();

function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS.en[key] || key;
}

function translateRewardName(name) {
  if (name === TRANSLATIONS.en.rewardName10fs) return t('rewardName10fs');
  if (name === TRANSLATIONS.en.rewardName20fs) return t('rewardName20fs');
  return name;
}

function applyLanguage() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if ('i18nHtml' in el.dataset) el.innerHTML = t(key);
    else el.textContent = t(key);
  });
  document.querySelectorAll('.lang-button').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
  renderLiveScreens();
}

function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'es') return;
  currentLang = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch (err) { /* storage unavailable */ }
  applyLanguage();
}

